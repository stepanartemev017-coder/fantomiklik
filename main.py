def cmd_stop(message):
    if message.chat.id in user_storage: user_storage[message.chat.id]['state'] = 'main'
    bot.send_message(message.chat.id, "🛑 **Режим ИИ выключен.**")

# --- ОБРАБОТКА ТЕКСТА ---
@bot.message_handler(func=lambda message: True)
def handle_text(message):
    cid = message.chat.id
    if cid not in user_storage: user_storage[cid] = {'history': [], 'state': 'main'}

    if user_storage[cid]['state'] == 'ai':
        bot.send_chat_action(cid, 'typing')
        user_storage[cid]['history'].append({"role": "user", "content": f"[ADMIN]: {message.text}"})
        
        try:
            completion = client.chat.completions.create(
                model="llama-3.3-70b-versatile",
                messages=[{"role": "system", "content": SYSTEM_PROMPT}] + user_storage[cid]['history'],
                temperature=0.85
            )
            answer = completion.choices[0].message.content
            user_storage[cid]['history'].append({"role": "assistant", "content": answer})
            if len(user_storage[cid]['history']) > 12: user_storage[cid]['history'] = user_storage[cid]['history'][-12:]
            bot.reply_to(message, answer)
        except Exception as e: bot.reply_to(message, f"Ошибка: {str(e)}")
    else: bot.send_message(cid, "Чтобы я начала помогать, введи /ai 🦾")

