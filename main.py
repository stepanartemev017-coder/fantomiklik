@bot.message_handler(func=lambda message: True)
def handle_all(message):
    cid = message.chat.id
    text = message.text

    if cid not in user_storage:
        user_storage[cid] = {'history': []}

    if text == "🤝 Знакомство":
        bot.send_message(cid, KNOWING_LIST, parse_mode="Markdown")
        return
    elif text == "🔥 Секстинг":
        bot.send_message(cid, SEXTING_LIST, parse_mode="Markdown")
        return
    elif text == "📝 Промты":
        bot.send_message(cid, ALL_PROMPTS_LIST, parse_mode="Markdown")
        return
    elif text == "🧼 Очистить память":
        user_storage[cid]['history'] = []
        bot.send_message(cid, "🧼 Память очищена. Я всё забыла... Начинаем заново!")
        return

    # Логика ИИ
    bot.send_chat_action(cid, 'typing')
    user_storage[cid]['history'].append({"role": "user", "content": text})
    
    try:
        completion = client.chat.completions.create(
            model="llama3-8b-8192",  # МОДЕЛЬ ИЗМЕНЕНА ДЛЯ УВЕЛИЧЕНИЯ ЛИМИТОВ
            messages=[{"role": "system", "content": SYSTEM_PROMPT}] + user_storage[cid]['history'],
            temperature=0.9
        )
        answer = completion.choices[0].message.content
        user_storage[cid]['history'].append({"role": "assistant", "content": answer})
        
        if len(user_storage[cid]['history']) > 15:
            user_storage[cid]['history'] = user_storage[cid]['history'][-15:]
            
        bot.reply_to(message, answer)
    except Exception as e:
        bot.reply_to(message, f"Ошибка: {str(e)}")

