def main_keyboard():
    markup = types.ReplyKeyboardMarkup(resize_keyboard=True, row_width=2)
    markup.add(
        types.KeyboardButton("💛 Знакомство"),
        types.KeyboardButton("🔞 Секстинг"),
        types.KeyboardButton("📝 Промты"),
        types.KeyboardButton("🧹 Очистить память")
    )
    return markup

@bot.message_handler(commands=['start', 'menu'])
def cmd_start(message):
    user_storage[message.chat.id] = {'history': []}
    bot.send_message(
        message.chat.id, 
        "<b>Эксперт по Fansly запущен.</b>\nЯ готов генерировать скрипты и помогать с продажами.", 
        reply_markup=main_keyboard(),
        parse_mode="HTML"
    )

@bot.message_handler(func=lambda message: True)
def handle_all(message):
    cid = message.chat.id
    text = message.text

    if cid not in user_storage:
        user_storage[cid] = {'history': []}

    # КНОПКА ЗНАКОМСТВО
    if "Знакомство" in text:
        res = "<b>💎 БАЗА: ЗНАКОМСТВО (нажми для копирования)</b>\n\n"
        for q in KNOWING_LIST:
            res += f"<code>{q}</code>\n"
        bot.send_message(cid, res, parse_mode="HTML")
        return

    # КНОПКА СЕКСТИНГ
    elif "Секстинг" in text:
        res = "<b>🔥 БАЗА: СЕКСТИНГ (нажми для копирования)</b>\n\n"
        for q in SEXTING_LIST:
            res += f"<code>{q}</code>\n"
        bot.send_message(cid, res, parse_mode="HTML")
        return

    # КНОПКА ПРОМТЫ
    elif "Промты" in text:
        res = "<b>📈 ПРОМТЫ ДЛЯ ПРОДАЖ (нажми для копирования)</b>\n\n"
        for q in ALL_PROMPTS_LIST:
            res += f"<code>{q}</code>\n\n"
        bot.send_message(cid, res, parse_mode="HTML")
        return

    # КНОПКА ОЧИСТКИ
    elif "Очистить" in text:
        user_storage[cid]['history'] = []
        bot.send_message(cid, "Память диалога очищена. Можем начинать заново.")
        return

    # ЛОГИКА ИИ (ОСНОВНАЯ ЧАСТЬ)
    bot.send_chat_action(cid, 'typing')
    user_storage[cid]['history'].append({"role": "user", "content": text})
    
    try:
        messages = [{"role": "system", "content": SYSTEM_PROMPT}] + user_storage[cid]['history']
        
        # Запрос к Groq
        completion = client.chat.completions.create(
            model="llama-3.1-8b-instant",
            messages=messages,
            temperature=0.7
        )

        # Получаем текст ответа (пофиксено через .message.content)
        answer = completion.choices[0].message.content
        
        user_storage[cid]['history'].append({"role": "assistant", "content": answer})
        
        # Обрезаем историю, чтобы не лагало (последние 16 сообщений)
        if len(user_storage[cid]['history']) > 16:
            user_storage[cid]['history'] = user_storage[cid]['history'][-16:]

        bot.reply_to(message, answer)
        
    except Exception as e:
        bot.reply_to(message, f"❌ Ошибка API: {str(e)}")

